function applyGrammarViOverrides(item) {
  const pat = PATTERN_OVERRIDES[item.id];
  const rawFormation = FORMATION_OVERRIDES[item.id] ?? item.formation ?? '';
  const formation = rawFormation
    .replace(/\bV-masu\b/g, 'Vます')
    .replace(/\bV-nai\b/g, 'Vない');

  return {
    ...item,
    pattern: pat ? pat.pattern : item.pattern,
    reading: pat ? pat.reading : item.reading,
    formation,
    nuanceVi: NUANCE_OVERRIDES[item.id] ?? item.nuanceVi,
  };
}

